/**
 * Filter countries based on user input (handles country code, dial code without plus, or country name)
 */
export function searchCountries(query: string): CountryCodeItem[] {
  const q = query.trim().toLowerCase();
  if (!q) return ALL_WORLD_COUNTRIES;

  const normalizedDigits = q.replace(/[^0-9]/g, '');

  return ALL_WORLD_COUNTRIES.filter((country) => {
    const nameMatch = country.name.toLowerCase().includes(q);
    const codeMatch = country.code.toLowerCase().includes(q);
    const dialCodeMatch = country.dialCode.toLowerCase().includes(q);
    const dialDigitsMatch = normalizedDigits.length > 0 && country.dialCode.replace(/[^0-9]/g, '').includes(normalizedDigits);

    return nameMatch || codeMatch || dialCodeMatch || dialDigitsMatch;
  });
}
